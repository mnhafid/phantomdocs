-- ShortenFlow — production readiness. Run section A first; run B only for what A shows missing.
-- Plain self-contained statements: no GO, no DECLARE, safe in a client that splits on ';'.
-- sys.* catalog views on purpose — INFORMATION_SCHEMA masks computed columns and reports
-- nvarchar byte-lengths, which has burned this project before.

-- ---------------------------------------------------------------------------
-- A. VERIFY (read-only)
-- ---------------------------------------------------------------------------

-- A1. The one table ShortenFlow adds. Expect 1 row; 0 rows means run B1.
SELECT o.name AS table_name, i.name AS unique_index
FROM sys.objects o
LEFT JOIN sys.indexes i ON i.object_id = o.object_id AND i.is_unique = 1
WHERE o.name = 'project_task_boq_drafts';

-- A2. Columns the draft read depends on. Expect 7 rows; any missing name = schema drift
--     that must be fixed from its own migration, not ad hoc here.
SELECT OBJECT_NAME(c.object_id) AS table_name, c.name AS column_name, t.name AS type_name
FROM sys.columns c
JOIN sys.types t ON t.user_type_id = c.user_type_id
WHERE (OBJECT_NAME(c.object_id) = 'project_tasks'  AND c.name IN ('spk_id','spk_type','start_date','end_date'))
   OR (OBJECT_NAME(c.object_id) = 'contracts'      AND c.name IN ('autogenerated_spk_number','retention_percentage'))
   OR (OBJECT_NAME(c.object_id) = 'boqs'           AND c.name = 'is_active')
ORDER BY table_name, column_name;

-- A3. Data precondition, not schema: how many production BOQs are flat (no header rows)?
--     parent_id can never resolve on those; fixing them is a BOQ re-upload, not SQL.
SELECT COUNT(DISTINCT b.id) AS active_boqs_without_headers
FROM boqs b
WHERE b.is_active = 1 AND b.deleted_at IS NULL
  AND NOT EXISTS (SELECT 1 FROM boq_details d WHERE d.boq_id = b.id AND d.data_type = 'header');

-- A4. Data precondition for the cancel repair (t7/D4): cancelled SPKs still holding live
--     task-BoQ lines. Rows here = run repair-cancelled-spk-task-boqs.sql (audit section first).
SELECT COUNT(DISTINCT s.spk_id) AS stale_cancelled_spks
FROM spks s
JOIN spk_boqs sb           ON sb.spk_id = s.spk_id
JOIN project_task_boqs ptb ON ptb.id = sb.project_task_boq_id AND ptb.deleted_at IS NULL
WHERE s.status = 'canceled';

-- ---------------------------------------------------------------------------
-- B. CREATE (only what A1 showed missing)
-- ---------------------------------------------------------------------------

-- B1. project_task_boq_drafts — identical to migration 20260817230252_AddProjectTaskBoqDrafts.
--     One draft per task (unique project_task_id); payload is the verbatim JSON the FE saved.
IF OBJECT_ID('project_task_boq_drafts') IS NULL
BEGIN
    CREATE TABLE project_task_boq_drafts
    (
        id              uniqueidentifier NOT NULL CONSTRAINT PK_project_task_boq_drafts PRIMARY KEY,
        project_task_id uniqueidentifier NOT NULL,
        contract_id     uniqueidentifier NOT NULL,
        payload         nvarchar(max)    NOT NULL,
        created_at      datetime         NOT NULL,
        created_by      uniqueidentifier NOT NULL,
        updated_at      datetime         NULL,
        updated_by      uniqueidentifier NULL
    );

    CREATE UNIQUE INDEX UX_project_task_boq_drafts_project_task_id
        ON project_task_boq_drafts (project_task_id);
END;

