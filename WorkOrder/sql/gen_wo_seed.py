def load(base, stage):
    return json.loads((SRC / f"{base}.{stage}.json").read_text())


def b64(obj):
    return base64.urlsafe_b64encode(json.dumps(obj, separators=(",", ":")).encode()).decode().rstrip("=")


def fake_jwt(sub, username, typ, tail):
    head = b64({"alg": "HS256", "typ": "JWT"})
    body = b64({"sub": sub, "preferred_username": username, "exp": 25340227560, "iss": "Phantom", "aud": "Phantom", "typ": typ})
    return f"{head}.{body}.{tail}-{username}"


def wo_acl(seqs):
    return [{"COMPONENTID": f"PHANTOM_{WO[s]}_Work Order", "URLPATH": "Work Order", "HIDDEN": 0, "READONLY": 0,
             "DISABLED": 0, "PAGE": WO[s], "SEQ": s} for s in seqs]


def build_role(dept, kind):
    base_acl = load(BASE[(dept, kind)], "token")["role"][0]["acl"]
    acl = [a for a in base_acl if a["SEQ"] not in WO and a["SEQ"] != 159]
    acl += [DATA_CONFIG] + wo_acl(WO_SEQ[kind])
    return {"SYSNAME": "PHANTOM", "SYSROLE": f"{DEPT[dept][1]} - {ROLE_NAME[kind]}", "acl": acl}


def roles_for(dept, kind):
    if kind == "gm":
        return [build_role(d, "manager") for d in ("po", "osf", "prj")]
    return [build_role(dept, kind)]


def patch_info(info, username, name, email, dept, pos):
    info.update({"USERID": username.upper(), "USERNAME": name, "EMAIL": email, "POSNAME": pos, "SUBFUNGSI": DEPT[dept][0]})
    return info


def sql_str(s):
    return "N'" + s.replace("'", "''") + "'"


def main():
    lines = [
        "-- Work Order FE test users (06-Test-Cases-and-Users.md §4). Mock auth only (R3tinaConfig:UseMockAuthSessions);",
        "-- the password is ignored. Cloned from the phirbac.role.* mock rows: own identity, tokens, SYSROLE and ACL.",
        "-- Re-runnable: every INSERT has WHERE NOT EXISTS. Generated by gen_wo_seed.py; do not edit by hand.",
        "",
        "-- 1. WO privileges 273-279 (groups 31, 32) ---------------------------------------------------------------",
        "INSERT INTO permission_groups (id, name, description, created_at, updated_at)",
        "SELECT v.id, v.name, v.name, GETDATE(), GETDATE()",
        "FROM (VALUES (31, 'Work Order'), (32, 'Work Order Approval')) v (id, name)",
        "WHERE NOT EXISTS (SELECT 1 FROM permission_groups g WHERE g.id = v.id);",
        "",
        "INSERT INTO permissions (id, permission_group_id, name, description, created_at)",
        "SELECT v.id, v.grp, v.name, v.description, GETDATE()",
        "FROM (VALUES",
        "    (273, 31, 'Read Work Order', 'View the Work Order pages'),",
        "    (274, 31, 'Create Work Order', 'Requestor: create, save as draft and submit a Work Order'),",
        "    (275, 31, 'Process Work Order', 'PIC of Level 1 / 2: disposition, create project, finish'),",
        "    (278, 31, 'Set Approval Flow', 'Target / assigned department: select the approval route of that department'),",
        "    (279, 31, 'Transfer Work Order', 'Target department: transfer the Work Order to the assigned department'),",
        "    (277, 32, 'Approve Work Order', 'User of the Work Order approval route (one layer, every Level)')",
        ") v (id, grp, name, description)",
        "WHERE NOT EXISTS (SELECT 1 FROM permissions p WHERE p.id = v.id);",
        "",
        "-- 2. Users and mock_auth_sessions (token, session, introspect) -------------------------------------------",
    ]
    tmpl_tok, tmpl_ses, tmpl_int = load("po.approval", "token"), load("po.approval", "session"), load("po.approval", "introspect")
    for suffix, username, dept, kind, pos, name in USERS:
        uid = f"0b000000-0000-0000-0000-000000000{suffix}"
        sub = f"00000000-0000-0000-0000-000000000{suffix}"
        email = f"{username}@yopmail.com"
        roles = roles_for(dept, kind)
        tok = copy.deepcopy(tmpl_tok)
        tok["access_token"] = fake_jwt(sub, username, "Bearer", "mock-bearer")
        tok["refresh_token"] = fake_jwt(sub, username, "Refresh", "mock-refresh")
        tok["session_state"] = f"mock-session-state-{username}"
        tok["users"] = {"name": name, "email": email, "username": username.upper()}
        tok["subfunc"], tok["posname"] = DEPT[dept][0], pos
        patch_info(tok["userInformation"], username, name, email, dept, pos)
        tok["role"] = roles
        ses = copy.deepcopy(tmpl_ses)
        patch_info(ses["userInformation"], username, name, email, dept, pos)
        ses["userInformation"]["USERNAME"] = username
        ses["roleInformation"] = {"role": roles}
        itr = copy.deepcopy(tmpl_int)
        itr.update({"jti": f"mock-jti-{username}", "sub": sub, "sid": tok["session_state"], "name": name,
                    "preferred_username": username, "given_name": "WO", "family_name": username[7:],
                    "email": email, "username": username})
        sysroles = " ; ".join(r["SYSROLE"] for r in roles)
        lines += [
            f"-- {username}: {sysroles}",
            "INSERT INTO dbo.users (id, full_name, email, username, retina_id, role_id, status, department, pos_name, position_name, is_active, is_contractor, created_at)",
            f"SELECT '{uid}', {sql_str(name)}, {sql_str(email)}, {sql_str(username.upper())}, {sql_str(username.upper())}, {DEPT[dept][2]}, N'active', {sql_str(DEPT[dept][0])}, {sql_str(pos)}, {sql_str(pos)}, 1, 0, SYSUTCDATETIME()",
            f"WHERE NOT EXISTS (SELECT 1 FROM dbo.users WHERE retina_id = {sql_str(username.upper())} AND deleted_at IS NULL);",
        ]
        for stage, payload in (("token", tok), ("session", ses), ("introspect", itr)):
            lines += [
                "INSERT INTO dbo.mock_auth_sessions (id, username, stage, payload, created_at)",
                f"SELECT NEWID(), {sql_str(username)}, N'{stage}', {sql_str(json.dumps(payload))}, SYSUTCDATETIME()",
                f"WHERE NOT EXISTS (SELECT 1 FROM dbo.mock_auth_sessions WHERE username = {sql_str(username)} AND stage = N'{stage}');",
            ]
        lines.append("")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(USERS)} users)")


main()
